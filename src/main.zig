const std     = @import("std");
const fs      = std.fs;
const mem     = std.mem;
const math    = std.math;
const process = std.process;

pub fn main() !void {
    // just get memory in pages and free all at the end
    var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena.deinit();
    const allocator = arena.allocator();

    // handle args
    var args = try process.argsAlloc(allocator);
    defer process.argsFree(allocator, args);

    if (args.len < 2) {
        std.debug.print("Expected path to binary file\n", .{});
        return;
    }

    const asm_file_path = args[1];
    std.debug.print("{s}:\n", .{asm_file_path});

    if (mem.endsWith(u8, fs.path.extension(asm_file_path), ".asm")) {
        std.debug.print("Expected binary file but got and .asm one!\n", .{});
        return;
    }

    // open file
    var asm_file_absolute_path: []u8 = asm_file_path;
    if (fs.path.isAbsolute(asm_file_absolute_path) == false) {
        const cwd = try fs.cwd().realpathAlloc(allocator, ".");
        asm_file_absolute_path = try fs.path.resolve(allocator, &[_][]const u8{ cwd, asm_file_path });
    }
    const asm_file = try fs.openFileAbsolute(asm_file_absolute_path, .{});
    defer asm_file.close();

    const asm_file_content = try asm_file.readToEndAlloc(allocator, math.maxInt(usize));
    std.debug.print("{any}", .{asm_file_content});
}

